function callbacks = createModelingCallbacks(onChange)
%CREATEMODELINGCALLBACKS The callback struct hairsim.hair.createModelingControlPanel
%   expects, each forwarding to onChange(kind, value) with kind one of
%   hairsim.app.hair.applyModelingChange's kinds -- so an entry needs a
%   single handler instead of five.

callbacks = struct( ...
    'RigidityChanged', @(value) onChange("rigidity", value), ...
    'LengthChanged', @(value) onChange("length", value), ...
    'DensityChanged', @(value) onChange("density", value), ...
    'ThicknessChanged', @(value) onChange("thickness", value), ...
    'ColorChanged', @(value) onChange("color", value));
end
