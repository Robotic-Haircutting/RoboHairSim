function auto = createAutoPanel(parentPanel, callbacks, config)
%CREATEAUTOPANEL The Auto controls inside an entry's center slot
%   (hairsim.app.view.createSessionControls): region / target length /
%   planner fields, Plan, plan status, Preview, Save Plan, Run, Pause /
%   Resume, Abort. Pure UI constructor: handles only.
%
%   callbacks: AutoSettingsChanged (any of the three fields; never plans),
%   Plan, Preview, SavePlan, Run, Pause, Resume, Abort.
%   config: PlannerOptions (string array, e.g. hairsim.planning.listRegionPlanners),
%   Planner (initial selection), Region, TargetHairLengthM.

arguments
    parentPanel
    callbacks (1, 1) struct
    config (1, 1) struct
end

for name = ["AutoSettingsChanged", "Plan", "Preview", "SavePlan", "Run", "Pause", "Resume", "Abort"]
    if ~isfield(callbacks, name) || ~isa(callbacks.(name), 'function_handle')
        error("hairsim:MissingControlCallback", "Missing Auto callback: %s", name);
    end
end
plannerOptions = string(config.PlannerOptions);
regionOptions = ["scalp_top_left", "scalp_top_right", "scalp_left", "scalp_right", "scalp_back"];

uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.935, 0.38, 0.045], 'String', 'Region', ...
    'BackgroundColor', 'w', 'HorizontalAlignment', 'left');
regionPopup = uicontrol(parentPanel, 'Style', 'popupmenu', 'Units', 'normalized', ...
    'Position', [0.40, 0.935, 0.54, 0.05], 'String', cellstr(regionOptions), ...
    'Value', indexOf(regionOptions, config.Region), ...
    'Callback', callbacks.AutoSettingsChanged, 'Tag', 'hairsimAutoRegionPopup');

uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.875, 0.55, 0.045], 'String', 'Target length (cm)', ...
    'BackgroundColor', 'w', 'HorizontalAlignment', 'left');
targetLengthEdit = uicontrol(parentPanel, 'Style', 'edit', 'Units', 'normalized', ...
    'Position', [0.64, 0.875, 0.30, 0.05], 'String', sprintf('%.1f', 100 * config.TargetHairLengthM), ...
    'HorizontalAlignment', 'left', 'Callback', callbacks.AutoSettingsChanged, 'Tag', 'hairsimAutoTargetEdit');

uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.815, 0.38, 0.045], 'String', 'Planner', ...
    'BackgroundColor', 'w', 'HorizontalAlignment', 'left');
plannerPopup = uicontrol(parentPanel, 'Style', 'popupmenu', 'Units', 'normalized', ...
    'Position', [0.40, 0.815, 0.54, 0.05], 'String', cellstr(plannerOptions), ...
    'Value', indexOf(plannerOptions, config.Planner), ...
    'Callback', callbacks.AutoSettingsChanged, 'Tag', 'hairsimAutoPlannerPopup');

planButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.735, 0.88, 0.065], 'String', 'Plan', ...
    'FontWeight', 'bold', 'Callback', callbacks.Plan, 'Tag', 'hairsimAutoPlanButton');

planStatusPanel = uipanel(parentPanel, 'Units', 'normalized', ...
    'Position', [0.04, 0.44, 0.92, 0.28], 'Title', 'Plan', 'BackgroundColor', 'w');
planStatusText = uicontrol(planStatusPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.06, 0.88, 0.88], 'String', 'No plan yet', ...
    'BackgroundColor', 'w', 'FontSize', 8, 'HorizontalAlignment', 'left', 'Tag', 'hairsimAutoPlanStatusText');

previewButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.365, 0.42, 0.06], 'String', 'Preview', 'Callback', callbacks.Preview, ...
    'Tag', 'hairsimAutoPreviewButton');
saveButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.52, 0.365, 0.42, 0.06], 'String', 'Save Plan...', 'Callback', callbacks.SavePlan, ...
    'Tag', 'hairsimAutoSaveButton');

runButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.26, 0.88, 0.07], 'String', 'Run', ...
    'FontWeight', 'bold', 'BackgroundColor', [0.80, 0.95, 0.82], ...
    'Callback', callbacks.Run, 'Tag', 'hairsimAutoRunButton');
pauseButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.18, 0.42, 0.06], 'String', 'Pause', ...
    'Callback', callbacks.Pause, 'Tag', 'hairsimAutoPauseButton');
resumeButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.18, 0.42, 0.06], 'String', 'Resume', 'Visible', 'off', ...
    'Callback', callbacks.Resume, 'Tag', 'hairsimAutoResumeButton');
abortButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.52, 0.18, 0.42, 0.06], 'String', 'Abort', ...
    'BackgroundColor', [1.00, 0.82, 0.72], 'Callback', callbacks.Abort, 'Tag', 'hairsimAutoAbortButton');

auto = struct('regionPopup', regionPopup, 'regionOptions', regionOptions, ...
    'targetLengthEdit', targetLengthEdit, 'plannerPopup', plannerPopup, 'plannerOptions', plannerOptions, ...
    'planButton', planButton, 'planStatusText', planStatusText, 'previewButton', previewButton, ...
    'saveButton', saveButton, 'runButton', runButton, 'pauseButton', pauseButton, ...
    'resumeButton', resumeButton, 'abortButton', abortButton);
end

function idx = indexOf(options, selected)
idx = find(string(options) == string(selected), 1);
if isempty(idx)
    idx = 1;
end
end
