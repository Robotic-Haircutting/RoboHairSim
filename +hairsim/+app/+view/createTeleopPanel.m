function teleop = createTeleopPanel(parentPanel, callbacks, config)
%CREATETELEOPPANEL The clipper-Teleoperation controls inside an entry's
%   center slot (hairsim.app.view.createSessionControls): region, target
%   length, key help, live readout, Home. Pure UI constructor: handles only.
%   callbacks: Home, TargetLengthChanged, RegionChanged (function handles).
%   config: TargetHairLengthM (initial guard-comb length), RegionOptions
%   (string array of region names; the popup adds "Whole head" = ""
%   first), Region (initial selection, "" = whole head).

arguments
    parentPanel
    callbacks (1, 1) struct
    config (1, 1) struct
end

for name = ["Home", "TargetLengthChanged", "RegionChanged"]
    if ~isfield(callbacks, name) || ~isa(callbacks.(name), 'function_handle')
        error("hairsim:MissingControlCallback", "Missing Teleop callback: %s", name);
    end
end
regionOptions = ["", config.RegionOptions(:)'];
regionValue = find(regionOptions == config.Region, 1);
if isempty(regionValue)
    regionValue = 1;
end
uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.935, 0.30, 0.045], 'String', 'Region', ...
    'BackgroundColor', 'w', 'HorizontalAlignment', 'left');
regionPopup = uicontrol(parentPanel, 'Style', 'popupmenu', 'Units', 'normalized', ...
    'Position', [0.40, 0.935, 0.54, 0.05], 'String', cellstr(["Whole head", regionOptions(2:end)]), ...
    'Value', regionValue, ...
    'Callback', callbacks.RegionChanged, 'Tag', 'hairsimTeleopRegionPopup');
uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.87, 0.55, 0.045], 'String', 'Target length (cm)', ...
    'BackgroundColor', 'w', 'HorizontalAlignment', 'left');
targetLengthEdit = uicontrol(parentPanel, 'Style', 'edit', 'Units', 'normalized', ...
    'Position', [0.64, 0.87, 0.30, 0.05], 'String', sprintf('%.1f', 100 * config.TargetHairLengthM), ...
    'HorizontalAlignment', 'left', 'Callback', callbacks.TargetLengthChanged, 'Tag', 'hairsimTeleopTargetEdit');
uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.48, 0.88, 0.38], 'BackgroundColor', 'w', 'FontSize', 8, ...
    'HorizontalAlignment', 'left', 'String', { ...
    'Click the 3D view first. The clipper rides the scalp:', ...
    '  W S / Up Down     push forward / pull back', ...
    '  A D / Left Right  slide sideways', ...
    '  Q E                turn the feed left / right', ...
    '  G                    feed against the hair flow', ...
    '  R F                lift / lower (lowest = touching)', ...
    '  Z X                roll the blade (edge cut)', ...
    '  C V                 slide along the rail (Rail setup)', ...
    '  hold Space        cut while pushing forward'});
poseText = uicontrol(parentPanel, 'Style', 'text', 'Units', 'normalized', ...
    'Position', [0.06, 0.17, 0.88, 0.30], 'String', 'Pose: -', ...
    'BackgroundColor', 'w', 'FontSize', 8, 'HorizontalAlignment', 'left', 'Tag', 'hairsimTeleopPoseText');
homeButton = uicontrol(parentPanel, 'Style', 'pushbutton', 'Units', 'normalized', ...
    'Position', [0.06, 0.05, 0.88, 0.10], 'String', 'Home', ...
    'Callback', callbacks.Home, 'Tag', 'hairsimTeleopHomeButton');
teleop = struct('regionPopup', regionPopup, 'regionOptions', regionOptions, ...
    'targetLengthEdit', targetLengthEdit, 'poseText', poseText, 'homeButton', homeButton);
end
