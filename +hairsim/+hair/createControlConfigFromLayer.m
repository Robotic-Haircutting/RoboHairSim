function config = createControlConfigFromLayer(hairLayer)
%CREATECONTROLCONFIGFROMLAYER Create GUI control values from a hair layer.

config = struct( ...
    'Rigidity', hairLayer.physics.rigidity, ...
    'LengthFactor', hairLayer.creation.hairLengthFactor, ...
    'DensityFactor', hairLayer.creation.hairDensityFactor, ...
    'Thickness', hairLayer.style.lineWidth, ...
    'HairColor', hairLayer.style.color);
end
