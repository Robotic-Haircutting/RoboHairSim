function [hairLayer, config] = createDefaultHairLayer( ...
        rootsPath, headMeshLocal, T_world_head, headScaleFactor)
%CREATEDEFAULTHAIRLAYER Create a hair layer from shared default settings.

config = hairsim.hair.createDefaultHairLayerConfig();
hairLayer = hairsim.hair.createHairLayer(rootsPath, ...
    headMeshLocal, T_world_head, headScaleFactor, ...
    'BaseNumStrands', config.baseNumStrands, ...
    'NumStrands', config.numStrands, ...
    'NodesPerStrand', config.nodesPerStrand, ...
    'HairLengthFactor', config.hairLengthFactor, ...
    'HairDensityFactor', config.hairDensityFactor, ...
    'RandomSeed', config.randomSeed, ...
    'Color', config.color, ...
    'Alpha', config.alpha, ...
    'LineWidth', config.lineWidth, ...
    'Gravity', config.gravity, ...
    'Rigidity', config.rigidity, ...
    'Damping', config.damping, ...
    'Dt', config.dt, ...
    'HeadClearanceM', config.headClearanceM, ...
    'PhysicsBatchSize', config.physicsBatchSize, ...
    'RenderBatchStride', config.renderBatchStride, ...
    'CutRadiusScale', config.cutRadiusScale);
end
