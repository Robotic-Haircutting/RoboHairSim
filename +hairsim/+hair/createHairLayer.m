function hairLayer = createHairLayer(rootsPath, headMeshLocal, ...
        T_world_head, headScaleFactor, options)
%CREATEHAIRLAYER Create reusable haircut state plus runtime layer settings.

arguments
    rootsPath
    headMeshLocal (1, 1) struct
    T_world_head (4, 4) double {mustBeFinite}
    headScaleFactor (1, 1) double {mustBePositive}
    options.BaseNumStrands (1, 1) double {mustBeInteger, mustBePositive} = 2200
    options.NumStrands (1, 1) double {mustBeInteger, mustBePositive} = 2200
    options.NodesPerStrand (1, 1) double {mustBeInteger, mustBePositive} = 12
    options.HairLengthFactor (1, 1) double {mustBePositive} = 1.0
    options.HairDensityFactor (1, 1) double {mustBePositive} = 1.0
    options.RandomSeed (1, 1) double {mustBeInteger} = 11
    options.Color (1, 3) double {mustBeFinite} = [0, 0, 0]
    options.Alpha (1, 1) double {mustBeNonnegative} = 0.25
    options.LineWidth (1, 1) double {mustBePositive} = 0.45
    options.Gravity (1, 3) double {mustBeFinite} = [0, 0, -0.0015]
    options.Rigidity (1, 1) double {mustBeNonnegative} = 0.5
    options.Damping (1, 1) double {mustBeNonnegative} = 0.95
    options.Dt (1, 1) double {mustBePositive} = 0.8
    options.HeadClearanceM (1, 1) double {mustBeNonnegative} = 0.001
    options.PhysicsBatchSize (1, 1) double {mustBeInteger, mustBePositive} = 24
    options.RenderBatchStride (1, 1) double {mustBeInteger, mustBePositive} = 8
    options.CutRadiusScale (1, 1) double {mustBePositive} = 1.0
end

requestedHairStrands = max(1, round(options.BaseNumStrands * options.HairDensityFactor));
requestedHairStrands = min(requestedHairStrands, options.NumStrands);
haircutState = hairsim.hair.createHaircutState(rootsPath, ...
    headMeshLocal, T_world_head, headScaleFactor, ...
    'BaseNumStrands', options.BaseNumStrands, ...
    'NumStrands', requestedHairStrands, ...
    'NodesPerStrand', options.NodesPerStrand, ...
    'HairLengthFactor', options.HairLengthFactor, ...
    'HairDensityFactor', options.HairDensityFactor, ...
    'RandomSeed', options.RandomSeed, ...
    'Color', options.Color, ...
    'Alpha', options.Alpha, ...
    'LineWidth', options.LineWidth);

hairLayer = struct();
hairLayer.rootsPath = rootsPath;
hairLayer.headMeshLocal = headMeshLocal;
hairLayer.T_world_head = T_world_head;
hairLayer.headScaleFactor = headScaleFactor;
hairLayer.haircutState = haircutState;
hairLayer.creation = struct( ...
    'baseNumStrands', options.BaseNumStrands, ...
    'numStrands', options.NumStrands, ...
    'nodesPerStrand', options.NodesPerStrand, ...
    'hairLengthFactor', options.HairLengthFactor, ...
    'hairDensityFactor', options.HairDensityFactor, ...
    'randomSeed', options.RandomSeed);
hairLayer.style = struct( ...
    'color', options.Color, ...
    'alpha', options.Alpha, ...
    'lineWidth', options.LineWidth);
hairLayer.physics = struct( ...
    'gravity', options.Gravity, ...
    'rigidity', options.Rigidity, ...
    'damping', options.Damping, ...
    'dt', options.Dt, ...
    'headClearanceM', options.HeadClearanceM, ...
    'batchSize', options.PhysicsBatchSize, ...
    'renderBatchStride', options.RenderBatchStride, ...
    'nextStrand', 1, ...
    'batchCounter', 0);
hairLayer.cutting = struct('cutRadiusScale', options.CutRadiusScale);
end
