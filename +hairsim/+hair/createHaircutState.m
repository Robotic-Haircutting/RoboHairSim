function haircutState = createHaircutState( ...
        rootsSource, headMeshLocal, T_world_head, headScaleFactor, options)
%CREATEHAIRCUTSTATE Create reusable guide-hair haircut state.

arguments
    rootsSource
    headMeshLocal (1, 1) struct
    T_world_head (4, 4) double
    headScaleFactor (1, 1) double {mustBePositive}
    options.BaseNumStrands (1, 1) double {mustBeInteger, mustBePositive} = 2200
    options.NumStrands (1, 1) double {mustBeInteger, mustBePositive} = 2200
    options.NodesPerStrand (1, 1) double {mustBeInteger, mustBeGreaterThan(options.NodesPerStrand, 1)} = 12
    options.HairLengthFactor (1, 1) double {mustBePositive} = 1.0
    options.HairDensityFactor (1, 1) double {mustBePositive} = 1.0
    options.RandomSeed (1, 1) double = 11
    options.Gravity (1, 3) double = [0, 0, -0.0015]
    options.DebrisGravity (1, 3) double = [nan, nan, nan]
    options.Rigidity (1, 1) double = 0.5
    options.Damping (1, 1) double = 0.95
    options.Dt (1, 1) double {mustBePositive} = 0.8
    options.Color (1, 3) double = [0, 0, 0]
    options.Alpha (1, 1) double = 0.25
    options.LineWidth (1, 1) double {mustBePositive} = 0.45
end

debrisGravity = options.DebrisGravity;
if any(isnan(debrisGravity))
    debrisGravity = options.Gravity * 0.25;
end

hairModelLocal = hairsim.hair.model.createHairModelFromRoots(rootsSource, ...
    'NumStrands', options.NumStrands, ...
    'NodesPerStrand', options.NodesPerStrand, ...
    'HairLengthFactor', options.HairLengthFactor, ...
    'RandomSeed', options.RandomSeed);
[hairGuideXWorld, hairGuideYWorld, hairGuideZWorld] = ...
    hairsim.hair.model.transformNormalizedHairModelGuidesToWorld( ...
        hairModelLocal, headMeshLocal, T_world_head, headScaleFactor);
hairState = hairsim.hair.dynamics.createGuideHairDynamicState( ...
    hairGuideXWorld, hairGuideYWorld, hairGuideZWorld, ...
    'GuideAttraction', hairModelLocal.guideAttraction, ...
    'GravityWeight', hairModelLocal.gravityWeight, ...
    'BendSoftness', hairModelLocal.bendSoftness);

debrisList = struct('X', {}, 'Y', {}, 'Z', {}, ...
    'vx', {}, 'vy', {}, 'vz', {}, 'isStopped', {}, 'stopAge', {});

params = struct( ...
    'baseNumStrands', options.BaseNumStrands, ...
    'numStrands', hairModelLocal.numStrands, ...
    'nodesPerStrand', options.NodesPerStrand, ...
    'hairLengthFactor', options.HairLengthFactor, ...
    'hairDensityFactor', options.HairDensityFactor, ...
    'randomSeed', options.RandomSeed, ...
    'gravity', options.Gravity, ...
    'debrisGravity', debrisGravity, ...
    'rigidity', options.Rigidity, ...
    'damping', options.Damping, ...
    'dt', options.Dt, ...
    'color', options.Color, ...
    'alpha', options.Alpha, ...
    'lineWidth', options.LineWidth);

haircutState = struct();
haircutState.hairModelLocal = hairModelLocal;
haircutState.hairState = hairState;
haircutState.referenceHairNodeCounts = hairState.activeNodeCounts;
haircutState.debrisList = debrisList;
haircutState.params = params;
haircutState.lineData = hairsim.hair.render.createHaircutLineData( ...
    hairState, haircutState.referenceHairNodeCounts, debrisList);
end
