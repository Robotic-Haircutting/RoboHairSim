function handles = createModelingControlPanel(parentPanel, config, callbacks)
%CREATEMODELINGCONTROLPANEL Create hair modeling controls.

validateRequiredFields(config, { ...
    'Rigidity', ...
    'LengthFactor', ...
    'DensityFactor', ...
    'Thickness', ...
    'HairColor'});
validateRequiredFields(callbacks, { ...
    'RigidityChanged', ...
    'LengthChanged', ...
    'DensityChanged', ...
    'ThicknessChanged', ...
    'ColorChanged'});

handles = struct();
currentHairColor = config.HairColor;

[handles.rigiditySlider, handles.rigidityLabel] = createSliderControl( ...
    parentPanel, [0.08, 0.89, 0.84, 0.06], [0.08, 0.82, 0.62, 0.06], ...
    [0.74, 0.82, 0.18, 0.06], ...
    'Hair Rigidity', 0.5, 1.5, config.Rigidity, ...
    callbacks.RigidityChanged);
[handles.lengthSlider, handles.lengthLabel] = createSliderControl( ...
    parentPanel, [0.08, 0.73, 0.84, 0.06], [0.08, 0.66, 0.62, 0.06], ...
    [0.74, 0.66, 0.18, 0.06], ...
    'Hair Length', 0.5, 2.0, config.LengthFactor, ...
    callbacks.LengthChanged);
[handles.densitySlider, handles.densityLabel] = createSliderControl( ...
    parentPanel, [0.08, 0.57, 0.84, 0.06], [0.08, 0.50, 0.62, 0.06], ...
    [0.74, 0.50, 0.18, 0.06], ...
    'Hair Density', 0.1, 2.0, config.DensityFactor, ...
    callbacks.DensityChanged);
[handles.thicknessSlider, handles.thicknessLabel] = createSliderControl( ...
    parentPanel, [0.08, 0.41, 0.84, 0.06], [0.08, 0.34, 0.62, 0.06], ...
    [0.74, 0.34, 0.18, 0.06], ...
    'Hair Thickness', 0.2, 3.0, config.Thickness, ...
    callbacks.ThicknessChanged);

uicontrol(parentPanel, 'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.08, 0.21, 0.84, 0.06], ...
    'String', 'Hair Color', ...
    'BackgroundColor', 'w', ...
    'FontWeight', 'bold');
handles.colorButton = uicontrol(parentPanel, 'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.08, 0.11, 0.84, 0.08], ...
    'String', 'Choose Hair Color', ...
    'Callback', @chooseHairColor, ...
    'BackgroundColor', currentHairColor, ...
    'ForegroundColor', createForegroundColor(currentHairColor));

    function chooseHairColor(~, ~)
        selectedColor = uisetcolor(currentHairColor, 'Choose Hair Color');
        if numel(selectedColor) ~= 3
            return;
        end
        currentHairColor = selectedColor;
        set(handles.colorButton, ...
            'BackgroundColor', currentHairColor, ...
            'ForegroundColor', createForegroundColor(currentHairColor));
        callbacks.ColorChanged(currentHairColor);
    end
end

function [sliderHandle, labelHandle] = createSliderControl( ...
        parentPanel, titlePosition, sliderPosition, valuePosition, ...
        titleText, minValue, maxValue, initialValue, callback)
uicontrol(parentPanel, 'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', titlePosition, ...
    'String', titleText, ...
    'BackgroundColor', 'w', ...
    'FontWeight', 'bold');
labelHandle = uicontrol(parentPanel, 'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', valuePosition, ...
    'String', sprintf('%.2f', initialValue), ...
    'BackgroundColor', 'w');
sliderHandle = uicontrol(parentPanel, 'Style', 'slider', ...
    'Units', 'normalized', ...
    'Position', sliderPosition, ...
    'Min', minValue, ...
    'Max', maxValue, ...
    'Value', initialValue, ...
    'Callback', @(src, ~) updateSliderValue(src, labelHandle, callback));
end

function updateSliderValue(src, labelHandle, callback)
value = get(src, 'Value');
set(labelHandle, 'String', sprintf('%.2f', value));
callback(value);
end

function foregroundColor = createForegroundColor(backgroundColor)
if mean(backgroundColor) < 0.5
    foregroundColor = [1, 1, 1];
else
    foregroundColor = [0, 0, 0];
end
end

function validateRequiredFields(inputStruct, requiredFields)
for fieldIdx = 1:numel(requiredFields)
    if ~isfield(inputStruct, requiredFields{fieldIdx})
        error("hairsim:MissingModelingControlPanelField", ...
            "Control panel input is missing field '%s'.", requiredFields{fieldIdx});
    end
end
end
