function haircutState = rebuildHaircutState( ...
        haircutState, rootsSource, headMeshLocal, T_world_head, headScaleFactor, options)
%REBUILDHAIRCUTSTATE Recreate guide hair after length or density changes.

arguments
    haircutState (1, 1) struct
    rootsSource
    headMeshLocal (1, 1) struct
    T_world_head (4, 4) double
    headScaleFactor (1, 1) double {mustBePositive}
    options.HairLengthFactor (1, 1) double = nan
    options.HairDensityFactor (1, 1) double = nan
end

params = haircutState.params;
if ~isnan(options.HairLengthFactor)
    params.hairLengthFactor = options.HairLengthFactor;
end
if ~isnan(options.HairDensityFactor)
    params.hairDensityFactor = options.HairDensityFactor;
end

requestedHairStrands = max(1, round(params.baseNumStrands * params.hairDensityFactor));
haircutState = hairsim.hair.createHaircutState(rootsSource, ...
    headMeshLocal, T_world_head, headScaleFactor, ...
    'BaseNumStrands', params.baseNumStrands, ...
    'NumStrands', requestedHairStrands, ...
    'NodesPerStrand', params.nodesPerStrand, ...
    'HairLengthFactor', params.hairLengthFactor, ...
    'HairDensityFactor', params.hairDensityFactor, ...
    'RandomSeed', params.randomSeed, ...
    'Gravity', params.gravity, ...
    'DebrisGravity', params.debrisGravity, ...
    'Rigidity', params.rigidity, ...
    'Damping', params.damping, ...
    'Dt', params.dt, ...
    'Color', params.color, ...
    'Alpha', params.alpha, ...
    'LineWidth', params.lineWidth);
end
