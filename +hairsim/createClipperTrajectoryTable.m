function trajectoryTable = createClipperTrajectoryTable(time, positions, eulers, cutFlag)
%CREATECLIPPERTRAJECTORYTABLE Create the shared clipper trajectory table.

trajectoryTable = table( ...
    time(:), ...
    positions(:, 1), ...
    positions(:, 2), ...
    positions(:, 3), ...
    eulers(:, 1), ...
    eulers(:, 2), ...
    eulers(:, 3), ...
    double(cutFlag(:)), ...
    'VariableNames', {'time','x','y','z','roll','pitch','yaw','cutFlag'});
end
